CREATE TABLE IF NOT EXISTS users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), name text NOT NULL,
  email text UNIQUE NOT NULL, password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'customer' CHECK(role IN ('customer','admin')),
  wallet_balance bigint NOT NULL DEFAULT 0 CHECK(wallet_balance>=0),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY, user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku text NOT NULL UNIQUE,
  name text NOT NULL, description text NOT NULL, category text NOT NULL,
  price bigint NOT NULL CHECK(price>0 AND price<=100000000),
  original_price bigint, stock integer NOT NULL CHECK(stock>=0),
  min_age integer NOT NULL DEFAULT 3 CHECK(min_age>=0), max_age integer NOT NULL DEFAULT 12 CHECK(max_age>=min_age),
  art text NOT NULL DEFAULT 'blocks', color text NOT NULL DEFAULT '#f4eddc',
  badge text, sort_order integer NOT NULL DEFAULT 0, active boolean NOT NULL DEFAULT true,
  embedding double precision[], embedding_model text, embedding_hash text,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_products_category_price ON products(category,price) WHERE active;
CREATE INDEX IF NOT EXISTS idx_products_sort ON products(sort_order,id) WHERE active;
CREATE TABLE IF NOT EXISTS orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), number bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
  user_id uuid NOT NULL REFERENCES users(id), total bigint NOT NULL CHECK(total>0),
  status text NOT NULL CHECK(status IN ('pending','paid','shipping','completed','cancelled')),
  payment_method text NOT NULL CHECK(payment_method IN ('cod','wallet')),
  address jsonb NOT NULL, request_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(user_id,request_key)
);
CREATE INDEX IF NOT EXISTS idx_orders_user_date ON orders(user_id,created_at DESC);
CREATE TABLE IF NOT EXISTS order_items (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, order_id uuid NOT NULL REFERENCES orders(id),
  product_id integer NOT NULL REFERENCES products(id), quantity integer NOT NULL CHECK(quantity>0),
  unit_price bigint NOT NULL CHECK(unit_price>0), UNIQUE(order_id,product_id)
);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON order_items(product_id);
CREATE TABLE IF NOT EXISTS payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), order_id uuid NOT NULL UNIQUE REFERENCES orders(id),
  amount bigint NOT NULL CHECK(amount>0), method text NOT NULL CHECK(method IN ('cod','wallet')),
  status text NOT NULL CHECK(status IN ('pending','paid','refunded','cancelled')),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS audit_logs (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, table_name text NOT NULL,
  record_id text NOT NULL, operation text NOT NULL, old_data jsonb, new_data jsonb,
  actor text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS notifications (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, user_id uuid REFERENCES users(id),
  audience text NOT NULL CHECK(audience IN ('all','admin','user')),
  title text NOT NULL, body text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS notification_reads (
  user_id uuid NOT NULL REFERENCES users(id), notification_id bigint NOT NULL REFERENCES notifications(id),
  PRIMARY KEY(user_id,notification_id)
);
CREATE TABLE IF NOT EXISTS benchmark_results (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, row_count integer NOT NULL,
  before_ms double precision NOT NULL, after_ms double precision NOT NULL,
  before_plan jsonb NOT NULL, after_plan jsonb NOT NULL, created_at timestamptz DEFAULT now()
);

CREATE OR REPLACE FUNCTION audit_changes() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE before_row jsonb; after_row jsonb;
BEGIN
  IF TG_OP<>'INSERT' THEN before_row=to_jsonb(OLD)-'embedding'; END IF;
  IF TG_OP<>'DELETE' THEN after_row=to_jsonb(NEW)-'embedding'; END IF;
  IF TG_OP='UPDATE' AND (before_row-'updated_at'-'embedding_model'-'embedding_hash') IS NOT DISTINCT FROM (after_row-'updated_at'-'embedding_model'-'embedding_hash') THEN RETURN NEW; END IF;
  INSERT INTO audit_logs(table_name,record_id,operation,old_data,new_data,actor)
  VALUES(TG_TABLE_NAME,COALESCE(after_row->>'id',before_row->>'id'),TG_OP,before_row,after_row,COALESCE(NULLIF(current_setting('app.actor',true),''),'database'));
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_products_audit ON products;
CREATE TRIGGER trg_products_audit AFTER INSERT OR UPDATE OR DELETE ON products FOR EACH ROW EXECUTE FUNCTION audit_changes();
DROP TRIGGER IF EXISTS trg_orders_audit ON orders;
CREATE TRIGGER trg_orders_audit AFTER INSERT OR UPDATE OR DELETE ON orders FOR EACH ROW EXECUTE FUNCTION audit_changes();

CREATE OR REPLACE FUNCTION product_events() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.price<OLD.price THEN
    INSERT INTO notifications(audience,title,body) VALUES('all','Giá mới, niềm vui mới!',NEW.name||' vừa giảm từ '||OLD.price||'đ xuống '||NEW.price||'đ.');
  END IF;
  IF NEW.stock<=5 AND OLD.stock>5 THEN
    INSERT INTO notifications(audience,title,body) VALUES('admin','Sản phẩm sắp hết hàng',NEW.name||' chỉ còn '||NEW.stock||' sản phẩm.');
  END IF;
  IF (NEW.name,NEW.description,NEW.category,NEW.min_age,NEW.max_age) IS DISTINCT FROM (OLD.name,OLD.description,OLD.category,OLD.min_age,OLD.max_age) THEN
    NEW.embedding=NULL; NEW.embedding_hash=NULL; NEW.embedding_model=NULL;
  END IF;
  NEW.updated_at=now(); RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_product_events ON products;
CREATE TRIGGER trg_product_events BEFORE UPDATE ON products FOR EACH ROW EXECUTE FUNCTION product_events();

CREATE OR REPLACE FUNCTION order_events() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO notifications(user_id,audience,title,body) VALUES(NEW.user_id,'user','Đơn hàng TJ-'||lpad(NEW.number::text,5,'0'), 'Trạng thái đơn hàng: '||NEW.status);
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_order_events ON orders;
CREATE TRIGGER trg_order_events AFTER INSERT OR UPDATE OF status ON orders FOR EACH ROW EXECUTE FUNCTION order_events();

CREATE OR REPLACE PROCEDURE place_order(
  IN p_user_id uuid, IN p_items jsonb, IN p_method text, IN p_address jsonb, IN p_request_key text,
  OUT p_order_id uuid, OUT p_total bigint
) LANGUAGE plpgsql AS $$
DECLARE item record; product products%ROWTYPE; user_row users%ROWTYPE;
BEGIN
  SELECT * INTO user_row FROM users WHERE id=p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Khách hàng không tồn tại'; END IF;
  SELECT id,total INTO p_order_id,p_total FROM orders WHERE user_id=p_user_id AND request_key=p_request_key;
  IF FOUND THEN RETURN; END IF;
  IF p_method NOT IN ('cod','wallet') THEN RAISE EXCEPTION 'Phương thức thanh toán không hợp lệ'; END IF;
  IF jsonb_typeof(p_items)<>'array' OR jsonb_array_length(p_items)=0 OR jsonb_array_length(p_items)>50 THEN RAISE EXCEPTION 'Giỏ hàng không hợp lệ'; END IF;
  IF EXISTS(SELECT 1 FROM jsonb_to_recordset(p_items) AS x(product_id int,quantity int) WHERE quantity IS NULL OR quantity<=0 OR quantity>20 OR product_id IS NULL) THEN RAISE EXCEPTION 'Số lượng không hợp lệ'; END IF;
  p_total=0;
  FOR item IN SELECT product_id,sum(quantity)::int quantity FROM jsonb_to_recordset(p_items) AS x(product_id int,quantity int) GROUP BY product_id ORDER BY product_id LOOP
    SELECT * INTO product FROM products WHERE id=item.product_id AND active FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Sản phẩm không tồn tại'; END IF;
    IF item.quantity>20 OR product.stock<item.quantity THEN RAISE EXCEPTION 'Không đủ tồn kho cho %',product.name; END IF;
    p_total=p_total+product.price*item.quantity;
  END LOOP;
  IF p_method='wallet' AND user_row.wallet_balance<p_total THEN RAISE EXCEPTION 'Số dư ví demo không đủ'; END IF;
  INSERT INTO orders(user_id,total,status,payment_method,address,request_key)
  VALUES(p_user_id,p_total,CASE WHEN p_method='wallet' THEN 'paid' ELSE 'pending' END,p_method,p_address,p_request_key) RETURNING id INTO p_order_id;
  FOR item IN SELECT product_id,sum(quantity)::int quantity FROM jsonb_to_recordset(p_items) AS x(product_id int,quantity int) GROUP BY product_id ORDER BY product_id LOOP
    SELECT * INTO product FROM products WHERE id=item.product_id;
    INSERT INTO order_items(order_id,product_id,quantity,unit_price) VALUES(p_order_id,item.product_id,item.quantity,product.price);
    UPDATE products SET stock=stock-item.quantity WHERE id=item.product_id;
  END LOOP;
  IF p_method='wallet' THEN UPDATE users SET wallet_balance=wallet_balance-p_total WHERE id=p_user_id; END IF;
  INSERT INTO payments(order_id,amount,method,status) VALUES(p_order_id,p_total,p_method,CASE WHEN p_method='wallet' THEN 'paid' ELSE 'pending' END);
END $$;

CREATE OR REPLACE PROCEDURE cancel_order(IN p_user_id uuid, IN p_order_id uuid, OUT p_status text) LANGUAGE plpgsql AS $$
DECLARE order_row orders%ROWTYPE; item record;
BEGIN
  PERFORM 1 FROM users WHERE id=p_user_id FOR UPDATE;
  SELECT * INTO order_row FROM orders WHERE id=p_order_id AND user_id=p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy đơn hàng'; END IF;
  IF order_row.status='cancelled' THEN p_status='cancelled'; RETURN; END IF;
  IF order_row.status NOT IN ('pending','paid') THEN RAISE EXCEPTION 'Đơn đang giao hoặc đã hoàn tất không thể hủy'; END IF;
  FOR item IN SELECT * FROM order_items WHERE order_id=p_order_id ORDER BY product_id LOOP
    UPDATE products SET stock=stock+item.quantity WHERE id=item.product_id;
  END LOOP;
  IF order_row.payment_method='wallet' THEN
    UPDATE users SET wallet_balance=wallet_balance+order_row.total WHERE id=p_user_id;
    UPDATE payments SET status='refunded',updated_at=now() WHERE order_id=p_order_id;
  ELSE UPDATE payments SET status='cancelled',updated_at=now() WHERE order_id=p_order_id;
  END IF;
  UPDATE orders SET status='cancelled' WHERE id=p_order_id; p_status='cancelled';
END $$;

-- Exact cosine similarity. No extension needed; only compares genuine Gemini embeddings.
CREATE OR REPLACE FUNCTION cosine_similarity(a double precision[],b double precision[]) RETURNS double precision LANGUAGE sql IMMUTABLE STRICT AS $$
  SELECT CASE WHEN array_length(a,1)<>array_length(b,1) THEN NULL ELSE
    sum(x*y)/NULLIF(sqrt(sum(x*x))*sqrt(sum(y*y)),0) END
  FROM unnest(a,b) AS t(x,y)
$$;
